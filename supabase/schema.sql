CREATE OR REPLACE FUNCTION public.get_booked_hours(p_fecha date)
RETURNS TABLE (hora text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT turnos.hora
  FROM public.turnos
  WHERE turnos.fecha = p_fecha
    AND turnos.estado <> 'cancelado';
$$;

REVOKE ALL ON FUNCTION public.get_booked_hours(date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_booked_hours(date) TO anon, authenticated;

