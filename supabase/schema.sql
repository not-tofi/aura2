-- Crear tablas para tipos y turnos
create table if not exists public.tipos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  precio numeric not null default 0,
  descripcion text not null default '',
  duracion text not null default '',
  imagen_url text,
  imagen_path text,
  created_at timestamptz not null default now()
);

alter table public.tipos
  add column if not exists descripcion text not null default '',
  add column if not exists duracion text not null default '',
  add column if not exists imagen_url text,
  add column if not exists imagen_path text,
  add column if not exists eliminado boolean not null default false;

create table if not exists public.turnos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  email text,
  telefono text not null,
  tipo_id bigint references public.tipos(id),
  fecha date not null,
  hora text not null,
  notas text,
  estado text not null default 'pendiente',
  forma_pago text,
  precio_pagado numeric,
  push_subscription jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  telefono text,
  preferencias text,
  observaciones text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.redes_sociales (
  id bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  url text not null check (url ~* '^https?://'),
  orden integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.disenios (
  id bigint generated by default as identity primary key,
  titulo text not null check (btrim(titulo) <> ''),
  descripcion text not null default '',
  categoria text not null default '',
  imagen_url text not null,
  imagen_path text not null,
  created_at timestamptz not null default now()
);

alter table public.turnos
  add column if not exists email text,
  add column if not exists forma_pago text,
  add column if not exists precio_pagado numeric,
  add column if not exists push_subscription jsonb;

CREATE OR REPLACE FUNCTION public.validar_tipo_turno_activo()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.tipo_id IS NOT NULL AND EXISTS (
    SELECT 1
    FROM public.tipos
    WHERE id = NEW.tipo_id AND eliminado
  ) THEN
    RAISE EXCEPTION 'El servicio seleccionado ya no está disponible para nuevas reservas.'
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS turnos_tipo_activo ON public.turnos;
CREATE TRIGGER turnos_tipo_activo
  BEFORE INSERT ON public.turnos
  FOR EACH ROW
  EXECUTE FUNCTION public.validar_tipo_turno_activo();

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.turnos'::regclass AND conname = 'turnos_forma_pago_check'
  ) THEN
    ALTER TABLE public.turnos
      ADD CONSTRAINT turnos_forma_pago_check
      CHECK (forma_pago IS NULL OR forma_pago IN ('efectivo', 'transferencia', 'cuenta_bancaria'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.turnos'::regclass AND conname = 'turnos_precio_pagado_check'
  ) THEN
    ALTER TABLE public.turnos
      ADD CONSTRAINT turnos_precio_pagado_check
      CHECK (precio_pagado IS NULL OR precio_pagado >= 0);
  END IF;

  ALTER TABLE public.turnos
    DROP CONSTRAINT IF EXISTS turnos_push_subscription_check;
  ALTER TABLE public.turnos
    ADD CONSTRAINT turnos_push_subscription_check
    CHECK (
      push_subscription IS NULL OR (
        jsonb_typeof(push_subscription) = 'object' AND
        push_subscription - 'endpoint' - 'keys' - 'expirationTime' = '{}'::jsonb AND
        push_subscription ? 'endpoint' AND
        push_subscription ? 'keys' AND
        (
          NOT (push_subscription ? 'expirationTime') OR
          jsonb_typeof(push_subscription -> 'expirationTime') IN ('null', 'number')
        ) AND
        jsonb_typeof(push_subscription -> 'endpoint') = 'string' AND
        jsonb_typeof(push_subscription -> 'keys') = 'object' AND
        (push_subscription -> 'keys') - 'p256dh' - 'auth' = '{}'::jsonb AND
        jsonb_typeof(push_subscription -> 'keys' -> 'p256dh') = 'string' AND
        jsonb_typeof(push_subscription -> 'keys' -> 'auth') = 'string' AND
        coalesce(push_subscription ->> 'endpoint', '') ~ '^https://' AND
        char_length(coalesce(push_subscription ->> 'endpoint', '')) BETWEEN 1 AND 2048 AND
        char_length(coalesce(push_subscription -> 'keys' ->> 'p256dh', '')) BETWEEN 1 AND 256 AND
        char_length(coalesce(push_subscription -> 'keys' ->> 'auth', '')) BETWEEN 1 AND 256
      )
    );
END $$;

create index if not exists turnos_fecha_idx on public.turnos (fecha);
